export const formatPrice = (value: number) => value.toLocaleString("fa-IR");

export const toMillion = (value: number) =>
  (value / 1_000_000).toLocaleString("fa-IR", { maximumFractionDigits: 1 });

export const discountPercent = (product: Product) =>
  product.oldPrice
    ? Math.round(((product.oldPrice - product.price) / product.oldPrice) * 100)
    : 0;

export const labelOf = (list: { key: string; label: string }[], key: string) =>
  list.find((item) => item.key === key)?.label ?? key;
